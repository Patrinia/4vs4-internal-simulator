/// <summary>
/// 게임 내 존재하는 특수 속성의 종류를 정의합니다.
/// (예: 유닛이 보유한 속성, 스킬이 조작하는 대상 속성)
/// </summary>
public enum AttributeType
{
    None = 0,
    YinYang = 1,   // 음/양 속성 (0~100 게이지)
    Dream = 2      // 꿈 속성 (추후 기믹 추가용)
}

/// <summary>
/// 스킬의 목적과 가상 플레이어(Bot)의 페르소나를 매칭하기 위한 성향 태그입니다.
/// </summary>
public enum TendencyType
{
    None = 0,
    Aggressive = 1,   // 공격 위주 (데미지)
    Defensive = 2,    // 방어 위주 (보호막, 버프)
    Heal = 3,         // 치유 위주 (HP 회복)
    Control = 4,      // 턴 스킵, 기절 등 제어 위주
    Utility = 5       // 게이지 조작, 진형 파괴 등 유틸리티 위주
}